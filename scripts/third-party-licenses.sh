# Writes THIRD_PARTY_LICENSES.md: the licence texts of the Go standard library
# and of every module linked into the mw-feed binary, copied verbatim.
# Run it from anywhere after changing the dependencies, then update NOTICE.
#
#   scripts/third-party-licenses.sh
#
# The Go licence is read from $(go env GOROOT)/LICENSE; set GO_LICENSE_FILE
# when your Go installation keeps it elsewhere.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/THIRD_PARTY_LICENSES.md"
go_license="${GO_LICENSE_FILE:-$(cd "$root/src" && go env GOROOT)/LICENSE}"
[ -r "$go_license" ] || { echo "cannot read the Go licence at $go_license (set GO_LICENSE_FILE)" >&2; exit 1; }

cd "$root/src"
modules="$(go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}' ./cmd/mw-feed | sort -u)"

{
  echo '# Third-party licences'
  echo
  echo 'mw-feed is licensed under the GNU GPL version 3 or later (see LICENSE). The binary'
  echo 'contains the components below, each under its own licence, reproduced here as'
  echo 'published by its authors. This file is generated by scripts/third-party-licenses.sh.'
  echo
  echo '## Go standard library and runtime'
  echo
  echo '~~~~~~'
  cat "$go_license"
  echo '~~~~~~'
  while IFS='|' read -r path version dir; do
    echo
    echo "## $path $version"
    for file in "$dir"/*; do
      name="$(basename "$file")"
      [ -f "$file" ] || continue
      case "${name,,}" in
        license|license.*|license-*|license_*|licence|licence.*|licence-*|licence_*|copying|copying.*) ;;
        *) continue ;;
      esac
      echo
      echo "### $name"
      echo
      echo '~~~~~~'
      cat "$file"
      echo '~~~~~~'
    done
  done <<< "$modules"
} > "$out"
echo "wrote $out"
